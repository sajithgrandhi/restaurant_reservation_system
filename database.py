def get_mongo_client(uri: str = None) -> MongoClient:
    """
    Get or create a thread-safe MongoClient instance.
    Uses connection pooling provided natively by PyMongo.
    """
    global _client
    if _client is None:
        target_uri = uri or Config.MONGO_URI
        try:
            _client = MongoClient(
                target_uri,
                serverSelectionTimeoutMS=5000,
                connectTimeoutMS=5000,
                socketTimeoutMS=10000,
                maxPoolSize=50,
                minPoolSize=5,
            )
        except Exception as exc:
            logger.error("Failed to initialize MongoClient: %s", exc)
            raise
    return _client


def get_db(db_name: str = None):
    """Return the database instance."""
    client = get_mongo_client()
    target_name = db_name or Config.MONGO_DB_NAME
    return client[target_name]


def get_reservations_collection():
    """Return the 'reservations' collection."""
    db = get_db()
    return db["reservations"]


def check_connection() -> dict:
    """
    Ping the MongoDB server to verify connectivity.
    Returns status dict with server info or error details.
    """
    try:
        client = get_mongo_client()
        # Ping the server
        result = client.admin.command("ping")
        server_info = client.server_info()
        return {
            "connected": True,
            "ping": result,
            "version": server_info.get("version", "unknown"),
            "database": Config.MONGO_DB_NAME,
            "uri_sanitized": sanitize_uri(Config.MONGO_URI),
        }
    except (ConnectionFailure, ServerSelectionTimeoutError) as err:
        return {
            "connected": False,
            "error": str(err),
            "database": Config.MONGO_DB_NAME,
            "uri_sanitized": sanitize_uri(Config.MONGO_URI),
        }
    except Exception as exc:
        return {
            "connected": False,
            "error": str(exc),
            "database": Config.MONGO_DB_NAME,
            "uri_sanitized": sanitize_uri(Config.MONGO_URI),
        }


def sanitize_uri(uri: str) -> str:
    """Mask credentials in MongoDB connection string for safe display."""
    if "@" in uri:
        try:
            protocol_part, rest = uri.split("://", 1)
            credentials, host_part = rest.split("@", 1)
            return f"{protocol_part}://****:****@{host_part}"
        except Exception:
            return "mongodb://[credentials-hidden]"
    return uri


def serialize_document(doc: dict) -> dict:
    """
    Convert MongoDB document into JSON-serializable format.
    Transforms ObjectId to str and datetime to ISO 8601 strings.
    """
    if not doc:
        return None
    serialized = {}
    for key, value in doc.items():
        if isinstance(value, ObjectId):
            serialized[key] = str(value)
        elif isinstance(value, datetime):
            serialized[key] = value.isoformat()
        elif isinstance(value, list):
            serialized[key] = [
                serialize_document(v) if isinstance(v, dict) else v for v in value
            ]
        elif isinstance(value, dict):
            serialized[key] = serialize_document(value)
        else:
            serialized[key] = value
    return serialized


def serialize_documents(docs) -> list:
    """Convert list of MongoDB documents into JSON-serializable list."""
    return [serialize_document(doc) for doc in docs]

